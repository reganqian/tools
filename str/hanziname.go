// 昵称生成器
type NicknameGenerator struct {
	r *rand.Rand
}

const (
	GenderMale   = "male"
	GenderFemale = "female"
)

func (g *NicknameGenerator) RandomIdentitiy(gender string) string {
	identities := []string{}
	if strings.ToLower(gender) == GenderMale {
		identities = maleAdjectives
	} else if strings.ToLower(gender) == GenderFemale {
		identities = femaleAdjectives
	} else {
		identities = adjectives
	}
	identity := identities[g.r.Intn(len(identities))]
	return identity
}

func (g *NicknameGenerator) RandomName(gender string) string {
	names := []string{}
	if strings.ToLower(gender) == GenderMale {
		names = maleNicknames
	} else if strings.ToLower(gender) == GenderFemale {
		names = femaleNicknames
	} else {
		names = nicknames
	}
	name := names[g.r.Intn(len(names))]
	return name
}

// NewNicknameGenerator 创建新的昵称生成器
func NewNicknameGenerator() *NicknameGenerator {
	return &NicknameGenerator{
		r: rand.New(rand.NewSource(time.Now().UnixNano())),
	}
}

// Generate 生成"X的Y"格式昵称
// X: 1-3个汉字的状态/情绪词
// Y: 1-2个汉字的称呼/身份词
func (g *NicknameGenerator) Generate(gender string) string {
	// 随机决定X的长度(1-3个汉字)
	// xLen := g.r.Intn(3) + 1

	// 生成X部分(状态/情绪)
	identity := g.RandomIdentitiy(gender)
	name := g.RandomName(gender)
	return identity + name
}

// 便捷函数
var defaultGenerator = NewNicknameGenerator()

func RandomNickname(gender string) string {
	return defaultGenerator.Generate(gender)
}

